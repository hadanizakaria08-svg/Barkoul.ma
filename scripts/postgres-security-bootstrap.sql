CREATE OR REPLACE FUNCTION private.is_admin()
RETURNS boolean
LANGUAGE sql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $function$
  SELECT EXISTS (
    SELECT 1 FROM public.profiles p
    WHERE p.id=(SELECT auth.uid()) AND p.role='admin'
  )
$function$;
GRANT EXECUTE ON FUNCTION private.is_admin() TO authenticated;

CREATE POLICY profiles_insert_own ON public.profiles
  FOR INSERT TO authenticated WITH CHECK (id=(SELECT auth.uid()) AND role='user');
CREATE POLICY profiles_read_own ON public.profiles
  FOR SELECT TO authenticated USING (id=(SELECT auth.uid()));
CREATE POLICY profiles_update_own ON public.profiles
  FOR UPDATE TO authenticated USING (id=(SELECT auth.uid())) WITH CHECK (id=(SELECT auth.uid()));

CREATE POLICY cargos_authenticated_read ON public.cargos
  FOR SELECT TO authenticated
  USING (status='open' OR owner_id=(SELECT auth.uid()));
CREATE POLICY cargos_public_open_read ON public.cargos
  FOR SELECT TO anon USING (status='open');
CREATE POLICY cargos_secure_insert ON public.cargos
  FOR INSERT TO authenticated WITH CHECK (owner_id=(SELECT auth.uid()) AND status='open');
CREATE POLICY cargos_secure_update ON public.cargos
  FOR UPDATE TO authenticated USING (owner_id=(SELECT auth.uid()));
CREATE POLICY cargos_secure_delete ON public.cargos
  FOR DELETE TO authenticated USING (owner_id=(SELECT auth.uid()));

CREATE POLICY negotiations_insert_self ON public.negotiations
  FOR INSERT TO authenticated WITH CHECK (proposer_id=(SELECT auth.uid()));
CREATE POLICY negotiations_read_parties ON public.negotiations
  FOR SELECT TO authenticated USING (
    proposer_id=(SELECT auth.uid())
    OR EXISTS (SELECT 1 FROM public.cargos c WHERE c.id=negotiations.cargo_id AND c.owner_id=(SELECT auth.uid()))
  );

CREATE POLICY documents_insert_owner ON public.driver_documents
  FOR INSERT TO authenticated WITH CHECK (driver_id=(SELECT auth.uid()));
CREATE POLICY documents_read_owner_or_admin ON public.driver_documents
  FOR SELECT TO authenticated USING (driver_id=(SELECT auth.uid()) OR (SELECT private.is_admin()));

CREATE POLICY profile_role_requests_insert_own ON public.profile_role_requests
  FOR INSERT TO authenticated WITH CHECK (user_id=(SELECT auth.uid()) AND status='pending');
CREATE POLICY profile_role_requests_read_parties ON public.profile_role_requests
  FOR SELECT TO authenticated USING (user_id=(SELECT auth.uid()));

