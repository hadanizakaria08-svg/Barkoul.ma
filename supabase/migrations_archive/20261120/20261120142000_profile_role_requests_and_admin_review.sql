-- Allow registered users to request the driver or cargo-owner role.
CREATE TABLE IF NOT EXISTS public.profile_role_requests (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  requested_role text NOT NULL CHECK (requested_role IN ('driver','owner')),
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected')),
  created_at timestamptz NOT NULL DEFAULT now(),
  reviewed_at timestamptz,
  reviewed_by uuid REFERENCES auth.users(id)
);
CREATE UNIQUE INDEX IF NOT EXISTS profile_role_requests_one_pending_per_user
ON public.profile_role_requests(user_id) WHERE status='pending';
ALTER TABLE public.profile_role_requests ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS profile_role_requests_read_parties ON public.profile_role_requests;
CREATE POLICY profile_role_requests_read_parties ON public.profile_role_requests
FOR SELECT TO authenticated USING (user_id=(SELECT auth.uid()) OR (SELECT private.is_admin()));
DROP POLICY IF EXISTS profile_role_requests_insert_own ON public.profile_role_requests;
CREATE POLICY profile_role_requests_insert_own ON public.profile_role_requests
FOR INSERT TO authenticated WITH CHECK (
 user_id=(SELECT auth.uid()) AND status='pending' AND reviewed_at IS NULL AND reviewed_by IS NULL
 AND EXISTS (SELECT 1 FROM public.profiles p WHERE p.id=(SELECT auth.uid()) AND p.role='user')
);
REVOKE ALL ON public.profile_role_requests FROM anon,authenticated;
GRANT SELECT,INSERT ON public.profile_role_requests TO authenticated;
GRANT USAGE,SELECT ON SEQUENCE public.profile_role_requests_id_seq TO authenticated;

CREATE OR REPLACE FUNCTION public.admin_review_role_request(p_request_id bigint,p_approve boolean)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path=''
AS $function$
DECLARE v_req public.profile_role_requests%ROWTYPE;
BEGIN
 IF NOT (SELECT private.is_admin()) THEN RAISE EXCEPTION 'Administrator access required'; END IF;
 SELECT * INTO v_req FROM public.profile_role_requests WHERE id=p_request_id FOR UPDATE;
 IF NOT FOUND THEN RAISE EXCEPTION 'Request not found'; END IF;
 IF v_req.status<>'pending' THEN RAISE EXCEPTION 'Request already reviewed'; END IF;
 IF p_approve THEN
   UPDATE public.profiles SET role=v_req.requested_role WHERE id=v_req.user_id;
   UPDATE public.profile_role_requests SET status='approved',reviewed_at=now(),reviewed_by=(SELECT auth.uid()) WHERE id=p_request_id;
 ELSE
   UPDATE public.profile_role_requests SET status='rejected',reviewed_at=now(),reviewed_by=(SELECT auth.uid()) WHERE id=p_request_id;
 END IF;
 INSERT INTO public.admin_audit_log(admin_id,action,target_table,target_id)
 VALUES((SELECT auth.uid()),CASE WHEN p_approve THEN 'role_request_approved' ELSE 'role_request_rejected' END,'profile_role_requests',p_request_id::text);
END;
$function$;
REVOKE ALL ON FUNCTION public.admin_review_role_request(bigint,boolean) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.admin_review_role_request(bigint,boolean) TO authenticated;
