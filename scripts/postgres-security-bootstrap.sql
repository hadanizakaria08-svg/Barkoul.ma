CREATE FUNCTION auth.uid()
RETURNS uuid
LANGUAGE sql
STABLE
AS $function$
  SELECT NULLIF(current_setting('request.jwt.claim.sub', true), '')::uuid
$function$;
GRANT EXECUTE ON FUNCTION auth.uid() TO anon, authenticated, service_role;

CREATE FUNCTION storage.foldername(p_name text)
RETURNS text[]
LANGUAGE sql
IMMUTABLE
AS $function$
  SELECT CASE
    WHEN p_name IS NULL OR array_length(string_to_array(p_name, '/'), 1) IS NULL
      THEN ARRAY[]::text[]
    WHEN array_length(string_to_array(p_name, '/'), 1) <= 1
      THEN ARRAY[]::text[]
    ELSE (string_to_array(p_name, '/'))[1:array_length(string_to_array(p_name, '/'), 1) - 1]
  END
$function$;
GRANT EXECUTE ON FUNCTION storage.foldername(text) TO anon, authenticated, service_role;

CREATE TABLE public.profiles (
  id uuid PRIMARY KEY REFERENCES auth.users(id),
  full_name text,
  phone text,
  role text NOT NULL DEFAULT 'user' CHECK (role IN ('user','driver','owner','admin')),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.cargos (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL,
  origin_city text NOT NULL,
  destination_city text NOT NULL,
  goods_type text NOT NULL,
  weight_text text,
  truck_type text NOT NULL,
  loading_date date,
  offered_price_mad numeric CHECK (offered_price_mad IS NULL OR offered_price_mad >= 0),
  notes text,
  status text NOT NULL DEFAULT 'open' CHECK (status IN ('open','pending','matched','completed','cancelled')),
  created_at timestamptz NOT NULL DEFAULT now(),
  owner_id uuid NOT NULL REFERENCES auth.users(id)
);

CREATE TABLE public.negotiations (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cargo_id bigint NOT NULL REFERENCES public.cargos(id),
  proposer_id uuid NOT NULL REFERENCES auth.users(id),
  proposed_price_mad numeric NOT NULL CHECK (proposed_price_mad > 0),
  message text,
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','accepted','rejected','countered')),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX negotiations_one_pending_per_driver_cargo
  ON public.negotiations(cargo_id, proposer_id) WHERE status='pending';

CREATE TABLE public.trips (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cargo_id bigint NOT NULL REFERENCES public.cargos(id),
  owner_id uuid NOT NULL REFERENCES auth.users(id),
  driver_id uuid NOT NULL REFERENCES auth.users(id),
  agreed_price_mad numeric NOT NULL CHECK (agreed_price_mad >= 0),
  status text NOT NULL DEFAULT 'agreed' CHECK (status IN ('agreed','loading','in_transit','delivered','cancelled')),
  last_latitude double precision,
  last_longitude double precision,
  location_updated_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX trips_one_active_per_cargo_idx
  ON public.trips(cargo_id) WHERE status <> 'cancelled';

CREATE TABLE public.driver_documents (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  driver_id uuid NOT NULL REFERENCES auth.users(id),
  document_type text NOT NULL,
  storage_path text NOT NULL,
  review_status text NOT NULL DEFAULT 'pending' CHECK (review_status IN ('pending','verified','rejected')),
  uploaded_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.profile_role_requests (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users(id),
  requested_role text NOT NULL CHECK (requested_role IN ('driver','owner')),
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected')),
  created_at timestamptz NOT NULL DEFAULT now(),
  reviewed_at timestamptz,
  reviewed_by uuid REFERENCES auth.users(id)
);
CREATE UNIQUE INDEX profile_role_requests_one_pending_per_user
  ON public.profile_role_requests(user_id) WHERE status='pending';

CREATE TABLE public.admin_users (
  user_id uuid PRIMARY KEY REFERENCES auth.users(id),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.admin_audit_log (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  admin_id uuid REFERENCES auth.users(id),
  action text NOT NULL,
  target_table text,
  target_id text,
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE public.commission_charges (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  trip_id bigint NOT NULL REFERENCES public.trips(id),
  payer_id uuid NOT NULL REFERENCES auth.users(id),
  payer_role text NOT NULL CHECK (payer_role IN ('owner','driver')),
  amount_mad numeric NOT NULL CHECK (amount_mad > 0),
  status text NOT NULL DEFAULT 'due' CHECK (status IN ('due','paid','waived')),
  payment_method text CHECK (payment_method IN ('cash','electronic')),
  payment_reference text,
  paid_at timestamptz,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (trip_id,payer_id)
);

CREATE TABLE storage.buckets (
  id text PRIMARY KEY,
  name text NOT NULL,
