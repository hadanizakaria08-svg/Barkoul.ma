-- Fixed commission ledger: 10 MAD cargo owner + 20 MAD driver after delivery.
CREATE TABLE IF NOT EXISTS public.commission_charges (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 trip_id bigint NOT NULL REFERENCES public.trips(id) ON DELETE CASCADE,
 payer_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
 payer_role text NOT NULL CHECK (payer_role IN ('owner','driver')),
 amount_mad numeric(10,2) NOT NULL CHECK (amount_mad > 0),
 status text NOT NULL DEFAULT 'due' CHECK (status IN ('due','paid','waived')),
 payment_method text CHECK (payment_method IN ('cash','electronic')),
 payment_reference text,
 paid_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now(),
 CONSTRAINT commission_charges_trip_payer_unique UNIQUE(trip_id,payer_id)
);
CREATE INDEX IF NOT EXISTS commission_charges_payer_status_idx ON public.commission_charges(payer_id,status);
ALTER TABLE public.commission_charges ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS commission_charges_read_parties ON public.commission_charges;
CREATE POLICY commission_charges_read_parties ON public.commission_charges
FOR SELECT TO authenticated USING (payer_id=(SELECT auth.uid()) OR (SELECT private.is_admin()));
REVOKE ALL ON public.commission_charges FROM anon,authenticated;
GRANT SELECT ON public.commission_charges TO authenticated;

CREATE OR REPLACE FUNCTION private.create_commission_charges_after_delivery()
RETURNS trigger LANGUAGE plpgsql SECURITY DEFINER SET search_path=''
AS $function$
BEGIN
 IF NEW.status='delivered' AND OLD.status IS DISTINCT FROM NEW.status THEN
  INSERT INTO public.commission_charges(trip_id,payer_id,payer_role,amount_mad)
  VALUES (NEW.id,NEW.owner_id,'owner',10),(NEW.id,NEW.driver_id,'driver',20)
  ON CONFLICT (trip_id,payer_id) DO NOTHING;
 END IF;
 RETURN NEW;
END;
$function$;
REVOKE ALL ON FUNCTION private.create_commission_charges_after_delivery() FROM PUBLIC,anon,authenticated;
DROP TRIGGER IF EXISTS create_commission_charges_after_delivery ON public.trips;
CREATE TRIGGER create_commission_charges_after_delivery AFTER UPDATE OF status ON public.trips
FOR EACH ROW EXECUTE FUNCTION private.create_commission_charges_after_delivery();

-- Reveal only the other party's phone after a trip has been agreed.
CREATE OR REPLACE FUNCTION private.get_trip_contact_impl(p_trip_id bigint)
RETURNS TABLE(full_name text,phone text,role text)
LANGUAGE plpgsql SECURITY DEFINER SET search_path=''
AS $function$
DECLARE v_trip public.trips%ROWTYPE; v_uid uuid := (SELECT auth.uid()); v_other uuid;
BEGIN
 IF v_uid IS NULL THEN RAISE EXCEPTION 'Authentication required'; END IF;
 SELECT * INTO v_trip FROM public.trips WHERE id=p_trip_id;
 IF NOT FOUND OR (v_uid<>v_trip.owner_id AND v_uid<>v_trip.driver_id) THEN RAISE EXCEPTION 'Trip contact unavailable'; END IF;
 IF v_trip.status='cancelled' THEN RAISE EXCEPTION 'Trip is cancelled'; END IF;
 v_other := CASE WHEN v_uid=v_trip.owner_id THEN v_trip.driver_id ELSE v_trip.owner_id END;
 RETURN QUERY SELECT p.full_name,p.phone,p.role FROM public.profiles p WHERE p.id=v_other;
END;
$function$;
REVOKE ALL ON FUNCTION private.get_trip_contact_impl(bigint) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION private.get_trip_contact_impl(bigint) TO authenticated;
CREATE OR REPLACE FUNCTION public.get_trip_contact(p_trip_id bigint)
RETURNS TABLE(full_name text,phone text,role text)
LANGUAGE plpgsql SECURITY INVOKER SET search_path=''
AS $function$ BEGIN RETURN QUERY SELECT * FROM private.get_trip_contact_impl(p_trip_id); END; $function$;
REVOKE ALL ON FUNCTION public.get_trip_contact(bigint) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.get_trip_contact(bigint) TO authenticated;

-- Admin records a payment only after verifying cash received or an external electronic reference.
CREATE OR REPLACE FUNCTION private.admin_record_commission_payment_impl(p_charge_id bigint,p_method text,p_reference text DEFAULT NULL)
RETURNS void LANGUAGE plpgsql SECURITY DEFINER SET search_path=''
AS $function$
DECLARE v_charge public.commission_charges%ROWTYPE;
BEGIN
 IF NOT (SELECT private.is_admin()) THEN RAISE EXCEPTION 'Administrator access required'; END IF;
 IF p_method NOT IN ('cash','electronic') THEN RAISE EXCEPTION 'Unsupported payment method'; END IF;
 IF p_method='electronic' AND NULLIF(btrim(p_reference),'') IS NULL THEN RAISE EXCEPTION 'Electronic payment requires a verified reference'; END IF;
 SELECT * INTO v_charge FROM public.commission_charges WHERE id=p_charge_id FOR UPDATE;
 IF NOT FOUND OR v_charge.status<>'due' THEN RAISE EXCEPTION 'Charge unavailable'; END IF;
 UPDATE public.commission_charges SET status='paid',payment_method=p_method,
  payment_reference=NULLIF(btrim(p_reference),''),paid_at=now() WHERE id=p_charge_id;
 INSERT INTO public.admin_audit_log(admin_id,action,target_table,target_id)
 VALUES((SELECT auth.uid()),'commission_payment_recorded','commission_charges',p_charge_id::text);
END;
$function$;
REVOKE ALL ON FUNCTION private.admin_record_commission_payment_impl(bigint,text,text) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION private.admin_record_commission_payment_impl(bigint,text,text) TO authenticated;
CREATE OR REPLACE FUNCTION public.admin_record_commission_payment(p_charge_id bigint,p_method text,p_reference text DEFAULT NULL)
RETURNS void LANGUAGE plpgsql SECURITY INVOKER SET search_path=''
AS $function$ BEGIN PERFORM private.admin_record_commission_payment_impl(p_charge_id,p_method,p_reference); END; $function$;
REVOKE ALL ON FUNCTION public.admin_record_commission_payment(bigint,text,text) FROM PUBLIC,anon;
GRANT EXECUTE ON FUNCTION public.admin_record_commission_payment(bigint,text,text) TO authenticated;
